function result=test_aod_core_gate()
%TEST_AOD_CORE_GATE Synthetic unit gate for profile grouping and mixed split.
cfg=aod_config();
T=table({'orbitA';'orbitA';'orbitA';'orbitA';'orbitB';'orbitB'}, ...
    [10;10;10;10;10;10],[20;20;20;20;20;20], ...
    [1;1;1;1;2;2],[.09;.03;.09;.03;.09;.03], ...
    [.01;.02;.03;.04;.05;.06],[.001;.002;.003;.004;.005;.006], ...
    [.18;.18;.18;.18;.32;.32],[1;5;7;5;7;7], ...
    'VariableNames',{'FileName','Lon','Lat','UTC','Height','Ext','Back','Depol','Type'});
P=integrate_aod_tall_profiles(T,cfg);
assert(P.profiles==2 && P.rows==6,'AOD:GateProfiles','Profile grouping failed.');
assert(abs(P.height_step_km-.06)<1e-4,'AOD:GateDz','Uniform dz validation failed.');
assert(abs(P.direct_profile_aod(1,1)-.0006)<1e-10,'AOD:GateDirect','Direct integral mismatch.');
f=(.18-cfg.depol_nondust)*(1+cfg.depol_dust)/((cfg.depol_dust-cfg.depol_nondust)*(1+.18));
expected=((44*.002*f)+(70*.002*(1-f)))*.06 + ...
    ((44*.004*f)+(70*.004*(1-f)))*.06 + ...
    ((44*.003*f)+(23*.003*(1-f)))*.06;
actual=P.component_profile_aod(1,5)+P.component_profile_aod(1,7);
assert(abs(actual-expected)<1e-10,'AOD:GateMixed','Mixed component reconstruction mismatch.');
assert(P.direct_profile_count_by_channel(1,8)&&P.component_profile_count_by_channel(2,8), ...
    'AOD:GateCount','Profile count channel missing.');
result=struct('status','PASS','profiles',P.profiles,'rows',P.rows,'height_step_km',P.height_step_km);
fprintf('AOD_CORE_GATE_PASS profiles=%d rows=%d dz_km=%.6f\n',P.profiles,P.rows,P.height_step_km);
end
