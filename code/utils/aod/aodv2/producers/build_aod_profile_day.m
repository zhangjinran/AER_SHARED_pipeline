function R=build_aod_profile_day(raw_path,date_ymd,output_path)
cfg=aod_apro_config(); assert(~isfile(output_path),'AOD:Overwrite','Candidate exists.');
fprintf('APRO_LOAD_BEGIN path=%s\n',raw_path);
S=load_aod_mat_retry(raw_path,'day'); files=S.day.files;
fprintf('APRO_LOAD_PASS orbits=%d\n',numel(files));
result=cell(numel(files),1); source_files=cell(numel(files),1); geometries=cell(numel(files),1);
for i=1:numel(files)
    A=files{i}; source_files{i}=char(A.filename);
    assert(numel(A.Lidar_Data_Altitudes)==399,'AOD:NativeGrid','Expected full 399-bin APro orbit.');
    [P,geometries{i}]=integrate_aod_apro_orbit(A,cfg);
    if i==1,sample_report=check_aod_apro_samples(A,P,geometries{i},cfg);end
    P.source_file_index=repmat(uint32(i),numel(P.profile_index),1); result{i}=P;
    fprintf('AOD_APRO_ORBIT %d/%d profiles=%d grid_valid=%d zero_aerosol=%d qc_present=%d\n', ...
        i,numel(files),numel(P.profile_index),nnz(P.valid_for_grid), ...
        nnz(P.valid_for_grid&P.aerosol_subbin_count==0),geometries{i}.qc_present);
end
assert(numel(unique(string(source_files)))==numel(source_files),'AOD:DuplicateOrbit','Repeated source filename.');
names=fieldnames(result{1}); R=struct();
for i=1:numel(names),vals=cellfun(@(p)p.(names{i}),result,'UniformOutput',false); R.(names{i})=vertcat(vals{:});end
R.source_files=source_files; R.geometry=geometries; R.manual_sample_report=sample_report;
R.meta=struct('schema_version','aod-profile-v2','product_key',cfg.profile_key,'date',date_ymd, ...
    'source',raw_path,'source_kind','global_native_APro_MAT','channels',{cfg.channels}, ...
    'reconstructed_columns',[5 7 8],'mixed_component_columns',{{'Type5_dust','Type5_PC','Type7_dust','Type7_marine'}}, ...
    'qc_used',all(cellfun(@(g)g.qc_present,geometries)), ...
    'qc_available_orbits',nnz(cellfun(@(g)g.qc_present,geometries)), ...
    'qc_policy','if_present_accept_0_1_16_18;otherwise_range_checks_only', ...
    'avd_planes','upper_and_lower_each_half_bin','non_aerosol','zero', ...
    'missing_or_no_signal','invalid_profile_not_zero','aerosol_scope','tropospheric_Type1_to_7', ...
    'profile_count',numel(R.profile_index),'common_valid_profiles',nnz(R.valid_for_grid), ...
    'zero_aerosol_profiles',nnz(R.valid_for_grid&R.aerosol_subbin_count==0), ...
    'averaging',cfg.averaging,'lidar_ratio',cfg.ccn.lidar_ratio, ...
    'depol_endpoints',[cfg.ccn.depol_nondust cfg.ccn.depol_dust], ...
    'time_units','TAI seconds since 1993-01-01; native Profile_Time center', ...
    'reference',cfg.reference);
AOD_PROFILE=R; %#ok<NASGU>
save(output_path,'AOD_PROFILE','-v7.3');
fprintf('AOD_PROFILE_PASS profiles=%d valid=%d output=%s\n',R.meta.profile_count,R.meta.common_valid_profiles,output_path);
end
